// Función de búsqueda y filtrado rápido sin distinción de tildes o mayúsculas
export function searchColombiaLocations(query: string, maxResults: number = 50): ColombiaLocation[] {
  const clean = (str: string) =>
    str
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .trim();

  const cleanQuery = clean(query);
  if (!cleanQuery) {
    return ALL_COLOMBIA_LOCATIONS.slice(0, maxResults);
  }

  const results = ALL_COLOMBIA_LOCATIONS.filter((loc) => {
    const cleanCity = clean(loc.city);
    const cleanDept = clean(loc.department);
    const cleanFull = clean(loc.displayName);
    return (
      cleanCity.includes(cleanQuery) ||
      cleanDept.includes(cleanQuery) ||
      cleanFull.includes(cleanQuery)
    );
  });

  // Priorizar coincidencias exactas o de inicio
  return results
    .sort((a, b) => {
      const aStarts = clean(a.city).startsWith(cleanQuery) ? 1 : 0;
      const bStarts = clean(b.city).startsWith(cleanQuery) ? 1 : 0;
      if (aStarts !== bStarts) return bStarts - aStarts;

      const aPop = a.isPopular ? 1 : 0;
      const bPop = b.isPopular ? 1 : 0;
      return bPop - aPop;
    })
    .slice(0, maxResults);
}
